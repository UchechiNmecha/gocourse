package main

import "fmt"

func main() {
	// Variable declaration and initialization

	var a, b int = 10, 3
	var result int

	// Addition
	result = a + b
	fmt.Println("Addition: ", result)

	// subtraction
	result = a - b
	fmt.Println("Subtraction: ", result)

	// Multipliication
	result = a * b
	fmt.Println("Multiplication: ", result)

	// Division
	result = a / b
	fmt.Println("Division: ", result)

	// Modulus
	result = a % b
	fmt.Println("Remainder: ", result)

}